# Isolated X5 continuous-outcome study. Does not change production defaults.
source('R/scalar_iv_population_experiment.R')
x5s_contract<-function()list(beta=c(.14,.12,.10,.08,.06),
 theta=c(.20,-.25,.30,.15,-.20),shift=.75,x_cols=paste0('X',1:5),
 settings=data.frame(a=c(.55,1.1,1.65,1.1),b=c(.075,.075,.075,.15)),
 Lambda=c(1.8,2,2.5,3,3.5),n=6000L,
 target='fixed-class pseudo-bounds; population targets must be recomputed')
x5s_oracle<-function(data,a,b,contract=x5s_contract()){
 x<-as.matrix(data[,contract$x_cols]);h<-drop(x%*%contract$beta)
 location<-drop(x%*%contract$theta)
 list(e=rep(.5,nrow(data)),pi0=plogis(h-a/2),pi1=plogis(h+a/2),
  gamma0=siv_gamma(data$Y-location,-b),
  gamma1=siv_gamma(data$Y-location-contract$shift,b))
}
x5s_generate<-function(n,a,b,seed,contract=x5s_contract()){
 stopifnot(n>=1,a>=0,b>=0,length(contract$beta)==5,length(contract$theta)==5)
 set.seed(seed)
 x<-matrix(qnorm(pnorm(-2)+runif(n*5)*siv_normalizer(0)),ncol=5)
 colnames(x)<-contract$x_cols
 z<-rbinom(n,1,.5);h<-drop(x%*%contract$beta)
 treatment<-rbinom(n,1,plogis(h+a*(z-.5)))
 eta<-z*(2*treatment-1)*b
 residual<-eta+qnorm(pnorm(-2-eta)+runif(n)*siv_normalizer(eta))
 d<-data.frame(Y=drop(x%*%contract$theta)+contract$shift*treatment+residual,
  T_obs=treatment,Z=z,x)
 nu<-x5s_oracle(d,a,b,contract)
 d$e_true<-nu$e;d$pi0_true<-nu$pi0;d$pi1_true<-nu$pi1
 d$gamma0_oracle<-nu$gamma0;d$gamma1_oracle<-nu$gamma1
 d
}
